# CC API paths where --from/--to expect epoch milliseconds (not ISO 8601).
EPOCH_MS_PATHS = {
    "/v1/queues/statistics",
    "/v1/agents/statistics",
    "/v1/agents/activities",
    "/v1/tasks",
}


def camel_to_kebab(name):
    """Convert camelCase to kebab-case."""
    s = re.sub(r'([a-z0-9])([A-Z])', r'\1-\2', name)
    return s.lower()


def kebab_to_go_var(name):
    """The variable a flag's value was held in when commands were generated Go.
    Parameters whose names map to the same variable share one flag, and the
    table keeps that sharing."""
    parts = name.split('-')
    var = parts[0] + ''.join(p.capitalize() for p in parts[1:])
    if var in ('type', 'range', 'map', 'func', 'var', 'return', 'select',
               'default', 'switch', 'case', 'break', 'continue', 'interface',
               'package', 'import', 'go', 'defer', 'chan', 'struct'):
        var += 'Val'
    return var


def kebab_to_pascal(name):
    """Convert kebab-case to PascalCase."""
    return ''.join(p.capitalize() for p in name.split('-'))


def go_string(s):
    """A Go interpreted string literal. JSON escaping is valid Go, and keeping
    non-ASCII text as UTF-8 avoids surrogate escapes Go rejects."""
    return json.dumps(s, ensure_ascii=False)


def redacts_secrets(collection_name, path):
    return any(path.startswith(p) for p in REDACTED_ROUTES.get(collection_name, ()))


def is_private_api(collection_name, path):
    return any(path.startswith(p) for p in PRIVATE_API_ROUTES.get(collection_name, ()))


def resolve_host(collection_name, path, default):
    """Return the host key for an endpoint (longest prefix wins)."""
    overrides = BASE_URL_OVERRIDES.get(collection_name, {})
    match = ""
    for prefix in overrides:
        if path.startswith(prefix) and len(prefix) > len(match):
            match = prefix
    return overrides[match] if match else default


def pagination_hints(cmd_name, query_names, is_calling):
    """Return how --paginate pages a GET, or None when the endpoint has no
    paging parameters and is not a list (a single-object GET would otherwise
    print only an array pulled out of it).

    The result is a dict: offset is (start, size, first index) or None for the
    area default, size_param names Contact Center's page size parameter, and
    query holds parameters that must be set while paging."""
    is_list = cmd_name == 'list' or cmd_name.startswith('list-')
    paging = {'offset': None, 'size_param': '', 'query': {}}
    if not is_calling:
        # AI Agent Studio lists page by limit/offset under "objects".
        if {'limit', 'offset'} <= query_names:
            paging['offset'] = ('offset', 'limit', 0)
            return paging
        if not is_list and not query_names & {'page', 'pageSize', 'size'}:
            return None
        if 'size' in query_names and 'pageSize' not in query_names:
            paging['size_param'] = 'size'
        # Without it the flow store returns a bare array with no page count.
        if 'includePagination' in query_names:
            paging['query']['includePagination'] = 'true'
        return paging
    if {'start', 'max'} <= query_names:
        return paging
    if {'offset', 'max'} <= query_names:
        paging['offset'] = ('offset', 'max', 0)
    elif {'startIndex', 'count'} <= query_names:
        paging['offset'] = ('startIndex', 'count', 1)
    elif 'max' in query_names:
        paging['offset'] = ('', 'max', 0)
    elif is_list:
        paging['offset'] = ('', '', 0)
    else:
        return None
    return paging


def build_operation(ep, collection_name, is_calling, default_host, group):
    """Return one endpoint as operation data.

    params lists path, query and header parameters in the order they are set on
    a request. Each names the flag that supplies it; a parameter whose name maps
    to an already declared flag reads that flag. body_fields name their flags
    the same way."""
    method = ep['method']
    path = ep['path']
    path_params = [dict(p) for p in ep.get('path_params', [])]
    query_params = [dict(p) for p in ep.get('query_params', [])]

    # Contact Center paths take the org UUID, which the CLI fills into --orgid.
    # So do /contacts/organizations/ paths in other collections (Postman: "orgId
    # used in path are the org UUIDs"). Query parameters keep their API name.
    if not is_calling or '/contacts/organizations/' in path:
        path = path.replace('{orgId}', '{orgid}')
        for p in path_params:
            if p['name'] == 'orgId':
                p['name'] = 'orgid'
        for p in query_params:
            if p['name'] == 'orgId':
                p['api_name'] = 'orgId'
                p['name'] = 'orgid'

    declared = {}  # flag variable → flag name
    params = []

    def declare(name, usage, kind='string'):
        var = kebab_to_go_var(camel_to_kebab(name))
        if var in declared:
            return declared[var], False
        declared[var] = camel_to_kebab(name)
        return declared[var], True

    for p in path_params:
        if p['name'] in HARDCODED_PATH_PARAMS:
            params.append({'name': p['name'], 'in': 'path', 'value': HARDCODED_PATH_PARAMS[p['name']]})
            continue
        flag, _ = declare(p['name'], p.get('description', ''))
        params.append({'name': p['name'], 'in': 'path', 'flag': flag,
                       'usage': p.get('description', '')})
    for p in query_params:
        flag, _ = declare(p['name'], p.get('description', ''))
        params.append({'name': p.get('api_name', p['name']), 'in': 'query', 'flag': flag,
                       'usage': p.get('description', '')})
    for h in ep.get('extra_headers', []):
        if h['name'] == AGENT_TOKEN_HEADER:
            # Shares the flag of an {agentId} path parameter when there is one.
            flag, _ = declare('agentId', h.get('description', ''))
            params.append({'name': h['name'], 'in': 'agent-token', 'flag': flag,
                           'usage': h.get('description', '')})
            continue
        flag, _ = declare(h['name'], h.get('description', ''))
        params.append({'name': h['name'], 'in': 'header', 'flag': flag,
                       'usage': h.get('description', '')})

    body = None
    if ep.get('has_body'):
        fields = []
        if not ep.get('complex_body'):
            for f in ep.get('body_fields', []):
                flag, new = declare(f['name'], '')
                if not new and f['type'] != 'string':
                    # A non-string field cannot share a parameter's text flag.
                    continue
                fields.append({'name': f['name'], 'flag': flag, 'type': f['type']})
        body = {'fields': fields}

    query_names = {p['name'] for p in query_params}
    has_from = 'from' in query_names
    time_range = ''
    if has_from:
        time_range = 'epoch-ms' if path in EPOCH_MS_PATHS else 'iso'

    skip_cmds = SKIP_COMMANDS.get(collection_name, {}).get(group, set())
    return {
        'group': group,
        'command': ep['command'],
        'aliases': ep.get('aliases') or [],
        'summary': ep.get('original_name', ep['command']),
        'description': ep.get('description', ''),
        'method': method,
        'path': path,
        'host': resolve_host(collection_name, ep['path'], default_host),
        'params': params,
        'body': body,
        'paging': pagination_hints(ep['command'], query_names, is_calling) if method == 'GET' else None,
        'time_range': time_range,
        'private': is_private_api(collection_name, ep['path']),
        'redact': redacts_secrets(collection_name, ep['path']),
        # This endpoint returns a non-JSON deletion acknowledgement. Restricting
        # Accept to application/json causes the service to reject it with HTTP 406.
        'accept': '*/*' if method == 'DELETE' and ep['path'] == '/v1/usage-reports/{reportId}' else '',
        'handwritten': ep['command'] in skip_cmds or group in SKIP_GROUPS.get(collection_name, set()),
    }


def render_operation(var, area, op):
    """Go source for one operation variable."""
    lines = [f'var {var} = &Operation{{']
    lines.append(f'\tID: {go_string(var)}, Area: {go_string(area)}, Group: {go_string(op["group"])}, Command: {go_string(op["command"])},')
    if op['aliases']:
        lines.append('\tAliases: []string{' + ', '.join(go_string(a) for a in op['aliases']) + '},')
    lines.append(f'\tSummary: {go_string(op["summary"])},')
    if op['description']:
        lines.append(f'\tDescription: {go_string(op["description"])},')
    lines.append(f'\tMethod: {go_string(op["method"])}, Path: {go_string(op["path"])}, Host: {HOST_CONSTANTS[op["host"]]},')
    if op['params']:
        lines.append('\tParams: []Param{')
        for p in op['params']:
            parts = [f'Name: {go_string(p["name"])}', f'In: {IN_CONSTANTS[p["in"]]}']
            if 'value' in p:
                parts.append(f'Value: {go_string(p["value"])}')
            else:
                parts.append(f'Flag: {go_string(p["flag"])}')
                if p.get('usage'):
                    parts.append(f'Usage: {go_string(p["usage"])}')
            lines.append('\t\t{' + ', '.join(parts) + '},')
        lines.append('\t},')
    if op['body'] is not None:
        if op['body']['fields']:
            lines.append('\tBody: &Body{Fields: []BodyField{')
            for f in op['body']['fields']:
                lines.append(f'\t\t{{Name: {go_string(f["name"])}, Flag: {go_string(f["flag"])}, Type: {go_string(f["type"])}}},')
            lines.append('\t}},')
        else:
            lines.append('\tBody: &Body{},')
    paging = op['paging']
    if paging is not None:
        parts = []
        if paging['offset'] is not None:
            start, size, first = paging['offset']
            parts.append(f'Offset: &OffsetPaging{{Start: {go_string(start)}, Size: {go_string(size)}, First: {first}}}')
        if paging['size_param']:
            parts.append(f'SizeParam: {go_string(paging["size_param"])}')
        if paging['query']:
            parts.append('Query: map[string]string{' + ', '.join(
                f'{go_string(k)}: {go_string(v)}' for k, v in sorted(paging['query'].items())) + '}')
        lines.append('\tPaging: &Paging{' + ', '.join(parts) + '},')
    if op['time_range']:
        lines.append(f'\tTimeRange: {TIME_RANGE_CONSTANTS[op["time_range"]]},')
    if op['private']:
        lines.append('\tPrivate: true,')
    if op['redact']:
        lines.append('\tRedact: true,')
    if op['accept']:
        lines.append(f'\tAccept: {go_string(op["accept"])},')
    if op['handwritten']:
        lines.append('\tHandwritten: true,')
    lines.append('}')
    return lines


IN_CONSTANTS = {'path': 'InPath', 'query': 'InQuery', 'header': 'InHeader', 'agent-token': 'InAgentToken'}
TIME_RANGE_CONSTANTS = {'iso': 'TimeISO', 'epoch-ms': 'TimeEpochMs'}


def operation_var(prefix, group, command, taken):
    """An exported, unique Go name for an operation."""
    name = prefix + kebab_to_pascal(group) + kebab_to_pascal(command)
    name = re.sub(r'[^A-Za-z0-9_]', '', name)
    base, n = name, 2
    while name in taken:
        name = f'{base}Dup{n}' if n > 2 else f'{base}Dup'
        n += 1
    taken.add(name)
    return name


def generate_area_file(collection_name, groups, taken):
    """Go source for one area's groups and operations."""
    area, prefix, is_calling, default_host = COLLECTIONS[collection_name]
    lines = [GENERATED_HEADER, '', 'package webexops', '']
    group_lines = [f'var {area}Groups = []Group{{']
    op_vars = []
    op_count = 0
    for group_data in groups:
        group = group_data['group']
        endpoints = group_data['endpoints']
        if not endpoints:
            continue
        aliases = GROUP_ALIASES.get(collection_name, {}).get(group, [])
        summary = GROUP_DESCRIPTIONS.get(collection_name, {}).get(group, f'{kebab_to_pascal(group)} commands')
        parts = [f'Name: {go_string(group)}']
        if aliases:
            parts.append('Aliases: []string{' + ', '.join(go_string(a) for a in aliases) + '}')
        parts.append(f'Summary: {go_string(summary)}')
        if group in SKIP_GROUPS.get(collection_name, set()):
            parts.append('Handwritten: true')
        group_lines.append('\t{' + ', '.join(parts) + '},')
        for ep in endpoints:
            op = build_operation(ep, collection_name, is_calling, default_host, group)
            var = operation_var(prefix, group, ep['command'], taken)
            lines.extend(render_operation(var, area, op))
            lines.append('')
            op_vars.append(var)
            op_count += 1
    group_lines.append('}')
    lines.extend(group_lines)
    lines.append('')
    lines.append(f'var {area}Operations = []*Operation{{')
    for var in op_vars:
        lines.append(f'\t{var},')
    lines.append('}')
    return '\n'.join(lines) + '\n', op_count


def remove_generated_go(directory):
    """Delete generated Go files, keeping handwritten ones."""
    if not os.path.isdir(directory):
        return
    for f in os.listdir(directory):
        path = os.path.join(directory, f)
        if not f.endswith('.go'):
            continue
        with open(path) as fh:
            first = fh.readline().strip()
        if first == GENERATED_HEADER:
            os.remove(path)


def main():
    with open(SPEC_PATH) as f:
        spec = json.load(f)

    os.makedirs(OPS_DIR, exist_ok=True)
    remove_generated_go(OPS_DIR)
    taken = set()
    for collection_name, groups in spec.items():
        if collection_name not in COLLECTIONS:
            print(f"Skipping unknown collection: {collection_name}")
            continue
        area = COLLECTIONS[collection_name][0]
        # Command packages used to hold generated code; only handwritten files remain.
        remove_generated_go(os.path.join(CLI_DIR, "cmd", area))
        source, count = generate_area_file(collection_name, groups, taken)
        with open(os.path.join(OPS_DIR, f'zz_{area}.go'), 'w') as f:
            f.write(source)
        print(f"{collection_name}: {count} operations → pkg/webexops/zz_{area}.go")

    result = subprocess.run(['gofmt', '-w', OPS_DIR], capture_output=True, text=True)
    if result.returncode != 0:
        print(f"gofmt error: {result.stderr}")
    print("\nDone. Run 'go build ./...' to verify.")


if __name__ == "__main__":
    main()
